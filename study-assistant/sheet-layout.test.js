/* 答题卡排版单元测试： node sheet-layout.test.js
   每句单独成一段，段首空两格（答题人自己敲的两个空格），一行 25 格。
   □ 表示空格子，| 分隔格子，一个格子里可能有两个标点。 */
const L=require('./sheet-layout.js');

let pass=0,fail=0;
function eq(name,got,want){
  const g=JSON.stringify(got),w=JSON.stringify(want);
  if(g===w){pass++;console.log('  ✓ '+name);}
  else{fail++;console.log('  ✗ '+name+'\n      得到 '+g+'\n      期望 '+w);}
}
function group(n){console.log('\n'+n);}
const lay=t=>L.toLines(L.build('  '+t).out);
const row=s=>s.split('|');
function check(name,input,want){
  const got=lay(input);
  eq(name,got,want);
  got.forEach((l,i)=>{ const n=l.split('|').length; if(i===0||n!==25) console.log('      第'+(i+1)+'行（'+n+'格）'+l); });
}

group('标准答案 T1—T13');
